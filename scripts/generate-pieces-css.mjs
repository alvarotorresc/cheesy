// Builds src/styles/pieces.css from the cburnett stylesheet that ships with chessground.
//
// The playable board styles `.cg-wrap piece.<role>.<color>`; the static mini boards use `.pc-<c><R>`.
// One rule per piece serves both selectors, so the images are never duplicated.
// Run with `pnpm pieces:css` and commit the result.
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL(
  '../node_modules/@lichess-org/chessground/assets/chessground.cburnett.css',
  import.meta.url,
);
const target = new URL('../src/styles/pieces.css', import.meta.url);

const roles = { pawn: 'P', knight: 'N', bishop: 'B', rook: 'R', queen: 'Q', king: 'K' };
const rule =
  /\.cg-wrap piece\.(\w+)\.(white|black)\s*\{\s*background-image:\s*(url\([^)]*\))\s*;?\s*\}/g;

const css = readFileSync(source, 'utf8');
const out = [
  '/* Generated by scripts/generate-pieces-css.mjs from chessground.cburnett.css. Do not edit. */',
];
let count = 0;
for (const [, role, color, url] of css.matchAll(rule)) {
  const code = `${color === 'white' ? 'w' : 'b'}${roles[role]}`;
  out.push(`.cg-wrap piece.${role}.${color},\n.pc-${code} {\n  background-image: ${url};\n}`);
  count++;
}
if (count !== 12) throw new Error(`Expected 12 piece rules, found ${count}`);
out.push('.pc {\n  background-size: cover;\n  background-repeat: no-repeat;\n}');
writeFileSync(target, out.join('\n\n') + '\n');
console.log(`pieces.css: ${count} rules`);
